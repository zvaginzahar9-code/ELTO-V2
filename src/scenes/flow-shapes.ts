/**
 * Состояния потока — по одному на сцену главной.
 *
 * Поток не повторяет один и тот же жест. В каждой сцене у него своя роль:
 *
 *   герой        диагональный крюк: входит сверху справа, вершиной
 *                указывает на заголовок, уходит вниз — первый жест
 *   манифест     камера влетает в поток: ближние нити расплываются в
 *                свечение под текстом
 *   изделие      наискось из правого верхнего угла в левый нижний —
 *                за стеклом, в котором стоит опора
 *   производство поток выпрямляется в линии конвейера и ускоряется
 *   знак         лента проходит сквозь знак ELTO, стягиваясь в нём в точку
 *   каталог      поток данных: быстрая диагональ от левого края к
 *                правому, тянется к строке под курсором
 *   подбор       пологая волна проходит сквозь карточки снизу
 *   доверие      поток отступает вдаль, к горизонту города
 *   финал        яркий луч проходит за карточкой формы
 *   подвал       поток уходит за край экрана сквозь знак ELTO
 *
 * Поток всегда идёт за содержимым: под текстом, но не поверх него.
 * Координаты — доли экрана; точки за краем нормальны. `l` — прогресс
 * сцены 0→1, пока она стоит в кадре.
 */

import type { FlowShape, V2 } from "@/motion/flow";

const lerp = (a: number, b: number, t: number) => a + (b - a) * t;
const lp = (a: V2, b: V2, t: number): V2 => [lerp(a[0], b[0], t), lerp(a[1], b[1], t)];
const pts = (a: V2[], b: V2[], t: number) => a.map((p, i) => lp(p, b[i], t));

